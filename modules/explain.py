def verdict(score: float) -> tuple[str, str]:
    """点数（0〜100の順位）を、読める言葉に直す。"""
    if score is None or pd.isna(score):
        return ("—", "grey")
    if score >= 80:
        return ("とても高い（上位20%）", "green")
    if score >= 60:
        return ("高い", "green")
    if score >= 40:
        return ("ふつう", "grey")
    if score >= 20:
        return ("低い", "orange")
    return ("とても低い（下位20%）", "red")


def describe(name: str, score: float, raw: dict) -> dict:
    """1つの小項目を、読める形にまとめて返す。"""
    what, getter, guide = SUBSCORES.get(name, (name, lambda r: None, ""))
    try:
        actual = getter(raw or {})
    except Exception:
        actual = None
    v, color = verdict(score)
    return {"名前": name, "何を測るか": what, "実数": actual or "—",
            "目安": guide, "点数": score, "評価": v, "色": color}
