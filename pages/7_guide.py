"""使い方と指標の読み方。

数字だけ出して意味を説明しないのは、使えないのと同じ。
このページは「何の指標か」「どう読むか」「どう使うか」を全部書く。
"""
from __future__ import annotations

import streamlit as st

st.title("📖 使い方")

st.markdown("""
このアプリの本筋は **発掘** です。東証の全上場3,707社から、
「配当が増え続けそうで、まだ市場に正しく評価されていない会社」を探して出します。

保有管理と資金の割り振りは、**見つけた銘柄をどこに入れるか**を決めるための受け皿です。
""")

tab1, tab2, tab3, tab4 = st.tabs(
    ["① 毎月の使い方", "② 指標の読み方", "③ スコアの仕組み", "④ データの出どころと限界"])

# ─────────────────────────────────────────────────────────
with tab1:
    st.subheader("トレード利益を入金したときの流れ")
    st.markdown("""
#### 1. 🔭 発掘 で候補を見る

「表示：新規のみ」にすると、**まだ持っていない・監視もしていない銘柄**だけが出ます。
ここが発掘の主目的です。

見るべき列は3つだけ。

| 列 | 何を見るか |
|---|---|
| **自己利回り順位** | 90%以上なら「この会社としては、めったにない高利回り」＝買い時の可能性 |
| **ヘム指数** | 1.00以上なら「高利回りなのに配当性向が低い」＝増配の余地がまだある |
| **連続増配** | 長いほど、配当を増やす姿勢が定着している |

**総合スコアだけ見ないこと。** 総合は6つの観点の合成なので、
「なぜ高いのか」は内訳（「採点の内訳も表示」にチェック）を見ないと分かりません。

#### 2. 📄 銘柄カルテ で1社ずつ確かめる

気になった銘柄を選ぶと、1枚で判断できる情報が出ます。

- **何をやっている会社か**（有価証券報告書の「事業の内容」）
- **株価と配当利回りの推移** — 利回りが上がったのが「株価下落」なのか「増配」なのかを確かめる
- **いくらで買えば目標利回りに届くか**（指値）
- **何が起きたら間違いだったと認めるか**（棄却条件）

棄却条件を書いてウォッチリストに保存すると、🚨 監視 が自動で見張ります。

#### 3. 💰 資金投入 で割り振る

入金額を入れると、スコアと業種の空き枠を見ながら配分案を出します。

- **口座（特定／NISA）** を選ぶと税引後の受取額が変わります
- 買ったら **「この内容で買った」** を押すと保有に反映されます

#### 4. 🚨 監視 で異変を見る

「いま判断が要るもの」（減配・指値到達）と、
「状態として続いているもの」（基準を外れた等）が分かれています。

**株価が下がったこと自体はアラートにしません。** 配当株では下落は買い場だからです。
""")

# ─────────────────────────────────────────────────────────
with tab2:
    st.subheader("指標の読み方")

    st.markdown("### 自己利回り順位（パーセンタイル）")
    st.info("""
**これは何か** — その銘柄**自身の過去7年**の配当利回りを並べたとき、
いまの利回りがどのあたりに位置するかを 0〜100% で表したものです。

**なぜ絶対利回りではないのか** — 「利回り4%」は業種によって意味が違います。
銀行の4%は普通、情報通信の4%は異常な高さです。同じ会社の過去と比べれば、
その会社にとって高いのか安いのかが分かります。

**読み方**

| 値 | 意味 |
|---|---|
| **90〜100%** | 自分史上まれに見る高利回り。株価が下がったか、大きく増配したか |
| 60〜90% | いつもより高い |
| 40〜60% | 平常どおり |
| 0〜40% | いつもより低い＝株価が買われている |

**注意** — 高いからといって必ず買いではありません。
**減配が近いから利回りが上がっている**場合もあります。
だから必ずカルテで「株価が下がったのか、配当が増えたのか」を確かめてください。
配当のグラフが右肩上がりなら増配が理由、株価チャートだけ落ちていれば下落が理由です。
""")

    st.markdown("### ヘム指数")
    st.info("""
**計算式** — 配当利回り × 10 ÷ 配当性向

個人投資家ヘムの基準「**配当性向 < 配当利回り × 10**」を、
満たす／満たさないの2択ではなく連続値にしたものです。
数学的には **PER 10倍以下** と同じ意味になります。

**なぜこの形なのか** — 高利回りと低配当性向を**同時に**要求するからです。

- 利回りだけ高い → 配当性向も高いことが多く、これ以上増やす余地がない
- 配当性向だけ低い → いま受け取れる配当が少ない
- **両方** → 「まだ配当を出し切っていない割安株」＝増配の余地が残っている

**読み方** — **1.00以上** で基準を満たします。数字が大きいほど余地が大きい。

**裏付け** — このアプリの検証では、単純に利回り上位30社を買うと
5年後のリターンは良い（+59.9%）が、**配当は5年で -3.8% と減っていました**。
配当性向で条件を付けないと「配当が育たない高利回り株」を掴みます。
ただし **ヘム指数で条件を付けると本当に改善するかは、まだ検証できていません**
（過去時点の配当性向データが必要なため）。
""")

    st.markdown("### 配当性向")
    st.info("""
**これは何か** — 稼いだ利益のうち、何%を配当に回したか。

**低いほど良いわけではありません。**

| 値 | 読み方 |
|---|---|
| 15%未満 | 株主に還元する気が薄い。増配を期待しにくい |
| **30〜50%** | 理想。増配の余地を残しつつ、きちんと還元している |
| 50〜70% | 出しすぎ気味。増配の余地は小さい |
| 70%超 | 利益が少し落ちただけで減配になる。このアプリでは足切り |

有価証券報告書が取れている銘柄は、**金融庁に提出された確定値**を使っています。
""")

    st.markdown("### 連続増配年数 / 減配なし継続年数")
    st.info("""
**連続増配年数** — 1株あたり配当が前年より増えた年が何年続いているか。
据え置き（同額）が1年でもあると途切れます。

**減配なし継続年数** — 減らさなかった年が何年続いているか。据え置きでは途切れません。
**累進配当**（減らさないと約束している会社）を拾うのはこちらです。

記念配当・特別配当で一時的に跳ねた年は、自動で検出して判定から除いています
（除かないと、記念配当の翌年に必ず「減配」が立ってしまうため）。

**重要** — このアプリの検証では、**連続増配年数は将来のリターンを説明しませんでした**。
連続増配の上位30社は、全銘柄を等分で持つより成績が悪かった（+32.8% 対 +39.5%）。
ただし**減配を避ける効果はあります**（減配発生率 49% 対 61%）。
だから加点ではなく、足切り条件として使っています。
""")

    st.markdown("### YOC（取得額に対する利回り）")
    st.info("""
**計算式** — いまの年間配当 ÷ **買ったときの金額**

いまの株価に対する利回り（現在利回り）とは別物です。
3%で買った株が増配を重ねれば、株価が上がっても **自分の受取率は5%、7%** と育ちます。
増配株を長期で持つ意味が、ここに数字で出ます。
""")

    st.markdown("### 発掘スコア と 配当継続スコア")
    st.warning("""
**この2つは別物です。混同しないでください。**

**発掘スコア（total）** — 「配当が増えそうで、**かつ市場にまだ気づかれていないか**」
新しい買い候補を探すためのスコア。見過ごされ度と割安さが入っているので、
**大型株は構造的に低く出ます**（三菱商事の見過ごされ度は8点、JR東日本は7点）。

**配当継続スコア（health）** — 「**配当が続くか・増えるか**」だけを見たスコア。
市場の評価は入れません。**持っている株を評価するのはこちら**です。

発掘スコアで保有を判断すると、累進配当で10年連続増配している三菱商事が
「スコアが低い」という理由だけで整理候補になります。それは誤りです。
""")

# ─────────────────────────────────────────────────────────
with tab3:
    st.subheader("スコアの仕組み")
    st.markdown("""
#### まず足切り（ゲート）

ここを通らない銘柄は、スコアすら計算しません。全3,707社のうち通るのは約700社です。

- 上場5年以上／時価総額100億円以上／20日平均売買代金3,000万円以上
- 直近10年の減配が1回以下／配当実績5年以上
- 営業キャッシュフローがプラスの期が75%以上／赤字が1期以下
- 自己資本比率30%以上、**または**（15%以上 かつ 有利子負債が営業CFの10年分以下）
- 配当性向70%以下／フリーキャッシュフローで配当を賄えている

財務の足切りを2本立てにしているのは、自己資本比率30%の一本槍だと
**通信・鉄道・電力が丸ごと落ちる**からです（NTTの自己資本比率は20.8%）。

#### 通った銘柄を6つの観点で採点

各観点は、**ゲートを通った約700社の中での順位**を0〜100点にしたものです。
50点は「ちょうど真ん中」を意味します。

| 観点 | 重み | 何を見るか |
|---|---|---|
| **割安** | 1.5 | 自己利回り順位・業種内の利回り・PER・PBR |
| **増配余力** | 1.5 | 配当性向・ヘム指数・FCFカバー率・ネットキャッシュ・負債の軽さ |
| **見過ごされ度** | 1.2 | 規模の小ささ・売買代金の薄さ・機関投資家保有の低さ・PBR1倍割れ×増益 |
| **原資成長** | 1.0 | EPSの伸び・営業CFの伸び・ROE・営業利益率 |
| **増配意思** | 0.5 | 連続増配・減配なし年数・DPS成長・**配当方針**（累進配当/DOE/性向目標） |
| **トラップ減点** | 引く | 異常高利回り×52週安値圏・利益とCFの乖離・配当性向の急上昇・希薄化 |

#### 重みの根拠

重みは勘で決めていません。**過去4時点・延べ9,220銘柄で検証した結果**にもとづきます。

- **割安が1.5** — 検証で唯一きれいに効いた。利回りで5分位に分けると、
  5年後リターンの中央値が **+15% → +65%** と単調に上がった
- **増配意思が0.5** — 加点としては効かなかった。連続増配の上位30社は市場平均に負けた
- **見過ごされ度が1.2** — 弱いが単調（+32% → +46%）
- **原資成長は1.0のまま** — 検証できていないので動かしていない

検証の中身は 🧪 検証 タブで自分で走らせて確かめられます。
""")

