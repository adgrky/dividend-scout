with tab4:
    st.subheader("データの出どころ")
    st.markdown("""
| データ | 出どころ | 取れる長さ |
|---|---|---|
| 上場銘柄・33業種区分 | JPX（日本取引所）公式の一覧 | 常に最新 |
| 株価・配当・株式分割 | yfinance の一括取得 | **2000年〜（26年分）** |
| 事業の内容・配当政策 | **EDINET**（金融庁）の有価証券報告書 | 最新の1年分 |
| EPS・配当性向・ROE・自己資本比率・営業CF | **EDINET** の「主要な経営指標等の推移」 | **5年分（確定値）** |
| 財務諸表（補助） | yfinance | 4〜5期分 |
| 権利確定日・会社予想配当 | yfinance | 直近 |
""")
    st.warning("""
#### 限界として知っておいてほしいこと

**1. yfinance の日本株データには誤りがあります。**
実測で、ある銘柄の配当性向が **480%** と返ってきました。
なので配当性向・ROE・自己資本比率は、**有価証券報告書が取れている銘柄では
そちらの確定値を使う**ようにしています。カルテに出どころを表示します。

**2. 株価データにも壊れた銘柄があります。**
全3,707社のうち39社で、古い株式分割が調整されずに残っていました
（ある銘柄は終値が553億円に跳ねていた）。破損している期間だけ自動で除いています。

**3. 検証できているのは一部の観点だけです。**
過去時点の財務データが再現できないため、**増配余力と原資成長は検証できていません**。
効くか分からない観点の重みは上げていません。

**4. これは自分用のツールです。**
スコアや推奨銘柄を他人に有償で提供すると投資助言業に当たります。
""")
    st.caption("配当の年度は、直近の権利落ち日を起点に1年ずつ遡ったまとまりで集計しています"
               "（日本企業は中間と期末に分けて払うため、暦年で足すと年度がずれるため）。"
               "これは実質的に「直近12ヶ月」であり、会計年度とは一致しません。")
